-- A signed-in user who is an enabled team member (row in sales, not disabled)
create or replace function public.is_team_member() returns boolean
    language plpgsql
    security definer
    stable
    set search_path to ''
    as $$
begin
  return exists (
    select 1 from public.sales
    where user_id = auth.uid() and disabled = false
  );
end;
$$;

-- Diner (B2C) data: admins and the support team only
create or replace function public.can_access_diners() returns boolean
    language plpgsql
    security definer
    stable
    set search_path to ''
    as $$
begin
  return exists (
    select 1 from public.sales
    where user_id = auth.uid()
      and disabled = false
      and (administrator = true or support = true)
  );
end;
$$;

revoke all on function public.is_team_member() from public;
grant execute on function public.is_team_member() to authenticated, service_role;
revoke all on function public.can_access_diners() from public;
grant execute on function public.can_access_diners() to authenticated, service_role;
grant all on function public.set_updated_at() to authenticated, service_role;
grant all on function public.handle_diner_tag_deleted() to authenticated, service_role;

