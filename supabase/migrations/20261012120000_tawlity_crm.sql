-- =============================================================================
-- Tawlity CRM
--   * Restaurants (companies) & restaurant contacts fields, holding groups
--   * Onboarding pipeline fields on deals, monthly fee in KWD (3 decimals)
--   * Account management fields (contract, plan, onboarding checklist, health)
--   * Diners (B2C app users), diner tags and diner notes / support interactions
--   * Support role on team members
--   * Row level security: data readable by signed-in team members only;
--     diners readable by admins and the support team only
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Restaurants (companies)
-- -----------------------------------------------------------------------------
alter table public.companies
    add column is_holding boolean not null default false,
    add column parent_company_id bigint,
    add column cuisines text[] not null default '{}',
    add column governorate text,
    add column area text,
    add column nb_branches integer,
    add column seating_capacity integer,
    add column price_range text,
    add column booking_system text,
    add column kga_member boolean not null default false,
    add column instagram_handle text,
    add column google_maps_url text,
    add column lead_source text,
    add column account_status text not null default 'prospect',
    add column contract_start_date date,
    add column renewal_date date,
    add column plan text,
    add column monthly_fee numeric(12, 3),
    add column onboarding_checklist jsonb not null default '{}'::jsonb,
    add column last_report_sent_at date,
    add column health text,
    add column health_note text;

alter table public.companies
    add constraint companies_parent_company_id_fkey foreign key (parent_company_id)
        references public.companies(id) on update cascade on delete set null,
    add constraint companies_not_own_parent check (parent_company_id is null or parent_company_id <> id),
    add constraint companies_monthly_fee_positive check (monthly_fee is null or monthly_fee >= 0),
    add constraint companies_health_check check (health is null or health in ('green', 'amber', 'red'));

create index companies_parent_company_id_idx on public.companies using btree (parent_company_id);
create index companies_account_status_idx on public.companies using btree (account_status);

