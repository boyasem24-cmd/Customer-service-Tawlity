create or replace view public.companies_summary with (security_invoker = on) as
select
    c.id,
    c.created_at,
    c.name,
    c.sector,
    c.size,
    c.linkedin_url,
    c.website,
    c.phone_number,
    c.address,
    c.zipcode,
    c.city,
    c.state_abbr,
    c.sales_id,
    c.context_links,
    c.country,
    c.description,
    c.revenue,
    c.tax_identifier,
    c.logo,
    count(distinct d.id) as nb_deals,
    count(distinct co.id) as nb_contacts,
    c.is_holding,
    c.parent_company_id,
    p.name as parent_company_name,
    (select count(*) from public.companies b where b.parent_company_id = c.id) as nb_brands,
    c.cuisines,
    c.governorate,
    c.area,
    c.nb_branches,
    c.seating_capacity,
    c.price_range,
    c.booking_system,
    c.kga_member,
    c.instagram_handle,
    c.google_maps_url,
    c.lead_source,
    c.account_status,
    c.contract_start_date,
    c.renewal_date,
    c.plan,
    c.monthly_fee,
    c.onboarding_checklist,
    c.last_report_sent_at,
    c.health,
    c.health_note
from public.companies c
    left join public.deals d on c.id = d.company_id
    left join public.contacts co on c.id = co.company_id
    left join public.companies p on p.id = c.parent_company_id
group by c.id, p.name;

create or replace view public.contacts_summary with (security_invoker = on) as
select
    co.id,
    co.first_name,
    co.last_name,
    co.gender,
    co.title,
    co.background,
    co.avatar,
    co.first_seen,
    co.last_seen,
    co.has_newsletter,
    co.status,
    co.tags,
    co.company_id,
    co.sales_id,
    co.linkedin_url,
    co.email_jsonb,
    co.phone_jsonb,
    (jsonb_path_query_array(co.email_jsonb, '$[*]."email"'))::text as email_fts,
    (jsonb_path_query_array(co.phone_jsonb, '$[*]."number"'))::text as phone_fts,
    c.name as company_name,
    count(distinct t.id) filter (where t.done_date is null) as nb_tasks,
    co.role,
    co.preferred_language,
    co.is_decision_maker
from public.contacts co
    left join public.tasks t on co.id = t.contact_id
    left join public.companies c on co.company_id = c.id
group by co.id, c.name;

