create table public.diner_tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.diners (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    first_name text not null,
    last_name text not null,
    phone text not null,
    phone_digits text generated always as (regexp_replace(phone, '\D', '', 'g')) stored,
    email extensions.citext,
    preferred_language text,
    gender text,
    signup_date date,
    signup_platform text,
    acquisition_source text,
    total_reservations integer not null default 0,
    total_no_shows integer not null default 0,
    total_cancellations integer not null default 0,
    last_booking_date date,
    favourite_restaurant_ids bigint[] not null default '{}',
    whatsapp_consent boolean not null default false,
    whatsapp_consent_date date,
    status text not null default 'active',
    tags bigint[] not null default '{}',
    constraint diners_counters_positive check (
        total_reservations >= 0 and total_no_shows >= 0 and total_cancellations >= 0
    ),
    constraint diners_status_check check (status in ('active', 'inactive', 'blocked'))
);

-- A phone number identifies a diner, whatever its formatting
create unique index diners_phone_digits_key on public.diners using btree (phone_digits);
create index diners_last_booking_date_idx on public.diners using btree (last_booking_date);
create index diners_status_idx on public.diners using btree (status);

create table public.diner_notes (
    id bigint generated by default as identity primary key,
    diner_id bigint not null,
    text text,
    date timestamp with time zone not null default now(),
    sales_id bigint,
    kind text not null default 'note',
    support_status text,
    constraint diner_notes_kind_check check (kind in ('note', 'support')),
    constraint diner_notes_support_status_check check (support_status is null or support_status in ('open', 'resolved'))
);

alter table public.diner_notes
    add constraint diner_notes_diner_id_fkey foreign key (diner_id) references public.diners(id) on update cascade on delete cascade,
    add constraint diner_notes_sales_id_fkey foreign key (sales_id) references public.sales(id);

create index diner_notes_diner_id_idx on public.diner_notes using btree (diner_id);

create or replace function public.set_updated_at() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace trigger set_diner_updated_at
    before update on public.diners
    for each row execute function public.set_updated_at();

create or replace trigger set_diner_notes_sales_id_trigger
    before insert on public.diner_notes
    for each row execute function public.set_sales_id_default();

create or replace function public.handle_diner_tag_deleted() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
  update public.diners set tags = array_remove(tags, old.id) where tags @> array[old.id];
  return old;
end;
$$;

create or replace trigger on_diner_tag_deleted
    after delete on public.diner_tags
    for each row execute function public.handle_diner_tag_deleted();

