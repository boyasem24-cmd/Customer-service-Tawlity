create schema if not exists "private";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb,
    -- Tawlity restaurant fields
    is_holding boolean not null default false,
    parent_company_id bigint,
    cuisines text[] not null default '{}',
    governorate text,
    area text,
    nb_branches integer,
    seating_capacity integer,
    price_range text,
    booking_system text,
    kga_member boolean not null default false,
    instagram_handle text,
    google_maps_url text,
    lead_source text,
    account_status text not null default 'prospect',
    -- Tawlity account management
    contract_start_date date,
    renewal_date date,
    plan text,
    monthly_fee numeric(12, 3),
    onboarding_checklist jsonb not null default '{}'::jsonb,
    last_report_sent_at date,
    health text,
    health_note text,
    constraint companies_not_own_parent check (parent_company_id is null or parent_company_id <> id),
    constraint companies_monthly_fee_positive check (monthly_fee is null or monthly_fee >= 0),
    constraint companies_health_check check (health is null or health in ('green', 'amber', 'red'))
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb,
    -- Tawlity restaurant contact fields
    role text,
    preferred_language text,
    is_decision_maker boolean not null default false
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    category text,
    stage text not null,
    description text,
    -- Monthly fee in KWD, with fils
    amount numeric(12, 3),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    plan text,
    nb_branches_covered integer,
    lost_reason text
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    -- Support team member: can see Diners data (like admins)
    support boolean not null default false,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

-- Diners: B2C users of the Tawlity app
create table public.diners (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    first_name text not null,
    last_name text not null,
    phone text not null,
    phone_digits text generated always as (regexp_replace(phone, '\D', '', 'g')) stored,
    email extensions.citext,
    preferred_language text,
    gender text,
    signup_date date,
    signup_platform text,
    acquisition_source text,
    total_reservations integer not null default 0,
    total_no_shows integer not null default 0,
    total_cancellations integer not null default 0,
    last_booking_date date,
    favourite_restaurant_ids bigint[] not null default '{}',
    whatsapp_consent boolean not null default false,
    whatsapp_consent_date date,
    status text not null default 'active',
    tags bigint[] not null default '{}',
    constraint diners_counters_positive check (
        total_reservations >= 0 and total_no_shows >= 0 and total_cancellations >= 0
    ),
    constraint diners_status_check check (status in ('active', 'inactive', 'blocked'))
);

create table public.diner_tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.diner_notes (
    id bigint generated by default as identity primary key,
    diner_id bigint not null,
    text text,
    date timestamp with time zone not null default now(),
    sales_id bigint,
    kind text not null default 'note',
    support_status text,
    constraint diner_notes_kind_check check (kind in ('note', 'support')),
    constraint diner_notes_support_status_check check (support_status is null or support_status in ('open', 'resolved'))
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

